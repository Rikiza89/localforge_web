let _currentLang = "en";

/**
 * Return translated string for key in current language.
 * Falls back to English, then to the key itself.
 */
function t(key, vars) {
  const dict = _TRANSLATIONS[_currentLang] || _TRANSLATIONS.en;
  let text = dict[key] || _TRANSLATIONS.en[key] || key;
  if (vars) {
    Object.keys(vars).forEach(k => {
      text = text.replace(new RegExp("\\{" + k + "\\}", "g"), vars[k]);
    });
  }
  return text;
}

/**
 * Apply translations to all elements with data-i18n / data-i18n-title /
 * data-i18n-placeholder attributes.
 */
function applyTranslations() {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    const val = t(key);
    if ((el.tagName === "INPUT" || el.tagName === "TEXTAREA") &&
        el.type !== "button" && el.type !== "submit") {
      el.placeholder = val;
    } else {
      el.textContent = val;
    }
  });
  document.querySelectorAll("[data-i18n-title]").forEach(el => {
    el.title = t(el.dataset.i18nTitle);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.documentElement.lang = _currentLang;
}

/**
 * Set language and persist to localStorage.
 * Dispatches a custom "languagechange" event.
 */
function setLanguage(lang) {
  if (!_SUPPORTED_LANGS.includes(lang)) lang = "en";
  _currentLang = lang;
  localStorage.setItem(_I18N_KEY, lang);
  applyTranslations();
  document.dispatchEvent(new CustomEvent("languagechange", { detail: { lang } }));
}

/** Return current language code. */
function getLanguage() { return _currentLang; }

/** Initialize i18n from localStorage or default to "en". */
function initI18n(projectLang) {
  const stored = projectLang || localStorage.getItem(_I18N_KEY) || "en";
  _currentLang = _SUPPORTED_LANGS.includes(stored) ? stored : "en";
  localStorage.setItem(_I18N_KEY, _currentLang);
  const sel = document.getElementById("lang-select");
  if (sel) sel.value = _currentLang;
  const reportLangSel = document.getElementById("report-language-select");
  if (reportLangSel) reportLangSel.value = _currentLang;
  applyTranslations();
}

// Auto-initialize on DOM ready (before project load; project load may call again with project lang)
if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", () => initI18n());
} else {
  initI18n();
}
